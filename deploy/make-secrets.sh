#!/bin/sh
# ساخت یک .env آمادهٔ تولید با رمزهای تصادفی.
#
# هر رمز جدا ساخته می‌شود و در یک فایل جدید نوشته می‌شود؛ فایل موجود
# بازنویسی نمی‌شود مگر --force داده شود.
#
#   sh deploy/make-secrets.sh            → .env.prod.local
#   sh deploy/make-secrets.sh --force    → بازنویسی
set -eu

out=".env.prod.local"
force=""
for arg in "$@"; do
  [ "$arg" = "--force" ] && force=1
done

if [ -f "$out" ] && [ -z "$force" ]; then
  echo "$out already exists — refusing to overwrite (use --force)" >&2
  exit 1
fi

# ۳۲ بایت تصادفی رمزنگاری‌شده → ۴۳ کاراکتر base64url.
# ترتیب مهم است: روی ویندوز `python3` یک shim فروشگاه مایکروسافت است که
# خطا می‌دهد، پس اول `python` امتحان می‌شود.
rand() {
  if command -v python >/dev/null 2>&1 && python -c "import secrets" 2>/dev/null; then
    python -c "import secrets; print(secrets.token_urlsafe(32))"
  elif command -v python3 >/dev/null 2>&1 && python3 -c "import secrets" 2>/dev/null; then
    python3 -c "import secrets; print(secrets.token_urlsafe(32))"
  elif command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 32 | tr -d '=+/' | cut -c1-43
  else
    echo "no working python, python3, or openssl found — cannot generate secrets" >&2
    exit 1
  fi
}

pg_password="$(rand)"
minio_password="$(rand)"
grafana_password="$(rand)"
backup_passphrase="$(rand)"
secret_key="$(rand)"
telegram_webhook_secret="$(rand)"

# کاراکترهای URL-unsafe باید escape شوند وگرنه DATABASE_URL خراب می‌شود
url_encode() {
  printf '%s' "$1" | od -An -tx1 -v | tr ' ' '\n' | grep -v '^$' |
    while read -r byte; do
      char="$(printf "\\$(printf '%03o' "0x$byte")")"
      case "$char" in
        [a-zA-Z0-9.~_-]) printf '%s' "$char" ;;
        *) printf '%%%02X' "0x$byte" ;;
      esac
    done
}

cat > "$out" <<EOF
# Generated by deploy/make-secrets.sh — keep this file out of git.
# Set as your production environment: cp $out .env

# --- Application ---
APP_ENV=production
DEBUG=false
SECRET_KEY=$secret_key
ACCESS_TOKEN_EXPIRE_MINUTES=15
REFRESH_TOKEN_EXPIRE_DAYS=14
COOKIE_SECURE=true
# Replace cm.example.com with your real host — it must be https, the
# startup guard rejects http origins.
CORS_ORIGINS=https://cm.example.com

# --- Database ---
POSTGRES_USER=cm
POSTGRES_PASSWORD=$pg_password
POSTGRES_DB=cm
# The host is the compose service name, not localhost.
DATABASE_URL=postgresql+asyncpg://cm:$(url_encode "$pg_password")@postgres:5432/cm

# --- Object storage ---
MINIO_ROOT_USER=cm
MINIO_ROOT_PASSWORD=$minio_password

# --- Monitoring ---
GF_SECURITY_ADMIN_PASSWORD=$grafana_password

# --- Backups ---
# Losing this means losing every backup. Store it in a password manager too.
BACKUP_PASSPHRASE=$backup_passphrase
BACKUP_RETENTION_DAYS=30

# --- Workers ---
WORKER_MODE=external
REDIS_URL=redis://redis:6379/0

# --- Optional integrations (leave empty/disabled until you configure them) ---
# The webhook secret is generated so the production startup guard passes; it
# only matters once TELEGRAM_MODE=webhook.
TELEGRAM_MODE=off
TELEGRAM_WEBHOOK_SECRET=$telegram_webhook_secret
BALE_MODE=off
DIVAR_MODE=fake
LDAP_ENABLED=false
SLA_USE_BUSINESS_CALENDAR=false
SLA_CHAIN_ESCALATION=false
REQUIRE_HUMAN_APPROVAL_FOR_SENSITIVE_AI=false
EOF

chmod 600 "$out" 2>/dev/null || true
echo "wrote $out (chmod 600) — review CORS_ORIGINS, then: cp $out .env"
